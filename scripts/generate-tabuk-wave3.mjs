  const markers = /    <!-- TABUK_WAVE3_LINKS_START -->[\s\S]*?    <!-- TABUK_WAVE3_LINKS_END -->/;
  html = markers.test(html) ? html.replace(markers, block) : html.replace('    <section class="section alt" id="journey">', `${block}\n    <section class="section alt" id="journey">`);
