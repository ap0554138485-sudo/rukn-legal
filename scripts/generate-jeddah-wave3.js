function updateSitemap() {
  const sitemapPath = path.join(root, 'sitemap.xml');
  let sitemap = fs.readFileSync(sitemapPath, 'utf8');
  const startMarker = '  <!-- JEDDAH_WAVE3_START -->';
  const endMarker = '  <!-- JEDDAH_WAVE3_END -->';
  const entries = services.map((service) => `  <url>
    <loc>${siteUrl}/${service.slug}</loc>
    <lastmod>${lastModified}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>${service.slug === 'legal-services-jeddah.html' ? '0.9' : '0.8'}</priority>
  </url>`).join('\n');
  const block = `${startMarker}\n${entries}\n${endMarker}`;
  const markerPattern = /  <!-- JEDDAH_WAVE3_START -->[\s\S]*?  <!-- JEDDAH_WAVE3_END -->/;
  sitemap = markerPattern.test(sitemap)
    ? sitemap.replace(markerPattern, block)
    : sitemap.replace(/\s*<\/urlset>\s*$/, `\n${block}\n</urlset>\n`);
  fs.writeFileSync(sitemapPath, sitemap, 'utf8');
}

